"""Operator-owned immutable ETHOS snapshots and scoped Compass analysis.

Documents are configuration, never generated by an agent or modified by a run.
One requirement is evaluated per call so attribution does not depend on parsing
model prose. Unsupported requirements are excluded before sending any evidence.
"""

from __future__ import annotations

import asyncio
