"""Render a local or mixed NIM council profile from the shipped policy template."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "configs/council.yaml"
ROLES = (
    "command-integrity",
    "environment-isolation",
    "blast-containment",
    "code_review",
    "chairman",
)
DEFAULT_MIXED_LOCAL_ROLES = ("command-integrity", "code_review", "chairman")
GENERATED_MARKER = (
    "# Generated by deploy/scripts/render-self-hosted-council.py; "
    "rerun the launcher to regenerate.\n"
)


def render(
    source: str, *, local_model: str, local_url: str, mode: str, local_roles: set[str]
) -> str:
    """Keep council policy unchanged while replacing backend definitions and role links."""
    if mode not in {"pure", "mixed"}:
        raise ValueError("mode must be pure or mixed")
    if not local_model or any(char in local_model for char in "\r\n"):
        raise ValueError("local model ID must be a nonempty single line")
    parsed = urlsplit(local_url)
    if (
        parsed.scheme not in {"http", "https"}
        or not parsed.hostname
        or parsed.path.rstrip("/") != "/v1"
    ):
        raise ValueError("local URL must be an http(s) /v1 base URL")
    if not local_roles.issubset(ROLES):
        raise ValueError(f"unknown roles: {', '.join(sorted(local_roles - set(ROLES)))}")
    if mode == "pure" and local_roles != set(ROLES):
        raise ValueError("pure mode must assign all roles to the local NIM")
    if mode == "mixed" and (not local_roles or local_roles == set(ROLES)):
        raise ValueError("mixed mode needs at least one local and one hosted role")

    section_start = source.index("llm_backends:\n")
    section_end = source.index("# ── Council Members", section_start)
    active = source[section_start:section_end]
    backend_start = active.index("  nim-kimi:\n")
    backend_end = active.index("  # Optional mixed-model example", backend_start)
    raw_backend = active[backend_start:backend_end]
    clean_lines = [
        line
        for line in raw_backend.splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    ]
    hosted_backend = "\n".join(clean_lines) + "\n"
    if hosted_backend.count('api_key: "${NVIDIA_API_KEY}"') != 1:
        raise ValueError("shipped backend no longer has the expected NVIDIA_API_KEY reference")
    model_line = next((line for line in clean_lines if line.startswith("    model: ")), None)
    url_line = next((line for line in clean_lines if line.startswith("    base_url: ")), None)
    if model_line is None or url_line is None:
        raise ValueError("shipped backend is missing model or base_url")

    local_backend = hosted_backend.replace("  nim-kimi:", "  nim-local:", 1)
    local_backend = local_backend.replace(model_line, f"    model: {json.dumps(local_model)}", 1)
    local_backend = local_backend.replace(url_line, f"    base_url: {json.dumps(local_url)}", 1)
    local_backend = local_backend.replace('api_key: "${NVIDIA_API_KEY}"', 'api_key: "local-nim"', 1)
    hosted_backend = hosted_backend.replace("  nim-kimi:", "  nim-hosted:", 1)
    backends = (
        "llm_backends:\n"
        "  # Local NIM accepts the non-secret client placeholder on a private network.\n"
    )
    backends += local_backend
    if mode == "mixed":
        backends += "\n  # NVIDIA API Catalog requires the real NVIDIA_API_KEY.\n" + hosted_backend
    backends += "\n"
    result = source[:section_start] + backends + source[section_end:]

    for role in ROLES:
        backend = "nim-local" if role in local_roles else "nim-hosted"
        if role in {"chairman", "code_review"}:
            pattern = rf"(?m)^({role}:\n  enabled: true\n  backend: )nim-kimi$"
        else:
            pattern = rf"(?m)^(  - id: {re.escape(role)}\n    backend: )nim-kimi$"
        result, count = re.subn(
            pattern, lambda match, backend=backend: match.group(1) + backend, result
        )
        if count != 1:
            raise ValueError(f"expected one backend assignment for {role}, found {count}")
    return GENERATED_MARKER + result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--local-model", required=True)
    parser.add_argument("--local-url", required=True)
    parser.add_argument("--mode", choices=("pure", "mixed"), required=True)
    parser.add_argument(
        "--local-roles",
        help=(
            "Comma-separated roles assigned to the local NIM in mixed mode; "
            "defaults to command-integrity,code_review,chairman"
        ),
    )
    args = parser.parse_args()
    if args.mode == "pure" and args.local_roles is not None:
        parser.error("--local-roles is only valid in mixed mode")
    roles = (
        set(ROLES)
        if args.mode == "pure"
        else set(args.local_roles.split(","))
        if args.local_roles is not None
        else set(DEFAULT_MIXED_LOCAL_ROLES)
    )
    if any(role != role.strip() or not role for role in roles):
        parser.error("--local-roles must contain nonempty role names without spaces")
    try:
        rendered = render(
            args.source.read_text(encoding="utf-8"),
            local_model=args.local_model,
            local_url=args.local_url,
            mode=args.mode,
            local_roles=roles,
        )
    except (OSError, ValueError) as exc:
        parser.error(str(exc))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(rendered, encoding="utf-8")
    print(f"Wrote {args.mode} council profile: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
