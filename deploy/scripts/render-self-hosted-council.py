"""Render a local or mixed NIM council profile from the shipped policy template."""

from __future__ import annotations

import argparse
import os
import tempfile
from pathlib import Path
from textwrap import indent
from urllib.parse import urlsplit

import yaml
from yaml.nodes import MappingNode, ScalarNode

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "configs/council.yaml"
ROLES = (
    "command-integrity",
    "environment-isolation",
    "blast-containment",
    "code_review",
    "chairman",
)
DEFAULT_MIXED_LOCAL_ROLES = ("command-integrity", "code_review", "chairman")
GENERATED_MARKER = (
    "# Generated by deploy/scripts/render-self-hosted-council.py; "
    "rerun the launcher to regenerate.\n"
)


class _UniqueKeyLoader(yaml.SafeLoader):
    """Reject ambiguous mappings instead of silently accepting duplicate fields."""

    def __init__(self, stream):
        super().__init__(stream)
        self.alias_fields = {}
        self.aliases = []
        self.anchored_nodes = set()
        self.anchor_names = set()

    def compose_node(self, parent, index):
        event = self.peek_event()
        is_alias = isinstance(event, yaml.AliasEvent)
        if is_alias and isinstance(index, ScalarNode):
            self.alias_fields[(id(parent), index.value)] = (
                event.start_mark.index,
                event.end_mark.index,
            )
        node = super().compose_node(parent, index)
        if is_alias:
            self.aliases.append((event, node))
        elif event.anchor is not None:
            self.anchored_nodes.add(id(node))
            self.anchor_names.add(event.anchor)
        return node

    def construct_mapping(self, node, deep=False):
        seen = set()
        for key, _value in node.value:
            name = self.construct_object(key, deep=deep)
            if not isinstance(name, str):
                raise ValueError("council YAML mapping keys must be strings")
            if name in seen:
                raise ValueError(f"duplicate YAML key: {name}")
            seen.add(name)
        return super().construct_mapping(node, deep=deep)


def _mapping(node, label):
    if not isinstance(node, MappingNode):
        raise ValueError(f"{label} must be a mapping")
    return {key.value: value for key, value in node.value}


def render(
    source: str, *, local_model: str, local_url: str, mode: str, local_roles: set[str]
) -> str:
    """Keep council policy unchanged while replacing backend definitions and role links."""
    if mode not in {"pure", "mixed"}:
        raise ValueError("mode must be pure or mixed")
    if not local_model or any(char in local_model for char in "\r\n"):
        raise ValueError("local model ID must be a nonempty single line")
    parsed = urlsplit(local_url)
    try:
        port = parsed.port
    except ValueError as exc:
        raise ValueError("local URL must be an http(s) /v1 base URL") from exc
    if (
        parsed.scheme not in {"http", "https"}
        or not parsed.hostname
        or port is None
        or port == 0
        or parsed.path.rstrip("/") != "/v1"
    ):
        raise ValueError("local URL must be an http(s) /v1 base URL")
    if not local_roles.issubset(ROLES):
        raise ValueError(f"unknown roles: {', '.join(sorted(local_roles - set(ROLES)))}")
    if mode == "pure" and local_roles != set(ROLES):
        raise ValueError("pure mode must assign all roles to the local NIM")
    if mode == "mixed" and (not local_roles or local_roles == set(ROLES)):
        raise ValueError("mixed mode needs at least one local and one hosted role")

    loader = _UniqueKeyLoader(source)
    try:
        document = loader.get_single_node()
        fields = _mapping(document, "council")
        config = loader.construct_document(document)
    except yaml.YAMLError as exc:
        raise ValueError(f"invalid council YAML: {exc}") from exc
    finally:
        loader.dispose()
    backends_node = fields.get("llm_backends")
    for name, node in _mapping(backends_node, "llm_backends").items():
        _mapping(node, f"backend {name}")
    hosted_backends = config["llm_backends"]
    if "nim-local" in hosted_backends:
        raise ValueError("source backend name nim-local is reserved for the generated local NIM")

    role_nodes = {}
    role_mappings = {}
    members = fields.get("members")
    if not isinstance(members, yaml.SequenceNode):
        raise ValueError("members must be a sequence")
    for member in members.value:
        member_fields = _mapping(member, "member")
        role = member_fields.get("id")
        if not isinstance(role, ScalarNode) or role.value not in ROLES[:3]:
            raise ValueError("members must use the three supported council voter IDs")
        if role.value in role_nodes:
            raise ValueError(f"duplicate council role: {role.value}")
        role_nodes[role.value] = member_fields.get("backend")
        role_mappings[role.value] = member
    for role in ("code_review", "chairman"):
        role_nodes[role] = _mapping(fields.get(role), role).get("backend")
        role_mappings[role] = fields[role]
    for role in ROLES:
        node = role_nodes.get(role)
        if not isinstance(node, ScalarNode) or node.value not in hosted_backends:
            raise ValueError(f"expected a defined backend assignment for {role}")
        if role in local_roles and (id(role_mappings[role]), "backend") in loader.alias_fields:
            raise ValueError(f"local role {role} backend must not be an alias")
        if role in local_roles and (
            id(node) in loader.anchored_nodes or id(role_mappings[role]) in loader.anchored_nodes
        ):
            raise ValueError(f"local role {role} must not use anchored YAML nodes")

    # Use the command reviewer's tuning for local inference, but always select
    # the NIM provider: a hosted backend may use a different provider protocol.
    local_backend = dict(hosted_backends[role_nodes["command-integrity"].value])
    local_backend.update(
        provider="nim",
        model=local_model,
        base_url=local_url,
        api_key="local-nim",  # pragma: allowlist secret
    )
    hosted_names = {node.value for role, node in role_nodes.items() if role not in local_roles}
    backends = {"nim-local": local_backend}
    backends.update(
        (name, backend) for name, backend in hosted_backends.items() if name in hosted_names
    )
    backend_key = next(key for key, _value in document.value if key.value == "llm_backends")
    # Collection end marks extend over trailing comments to the next key. Use
    # the last actual token instead; this also handles flow values and aliases
    # whose composed node marks point back to an earlier anchor definition.
    backend_end = max(
        token.end_mark.index
        for token in yaml.scan(source)
        if backend_key.start_mark.index <= token.start_mark.index < backends_node.end_mark.index
        and token.end_mark.index <= backends_node.end_mark.index
        and not isinstance(token, (yaml.BlockEndToken, yaml.StreamEndToken))
    )
    # Generated anchors must not collide with preserved source anchors, or
    # with anchors generated while materializing another alias below.
    reserved_anchors = set(loader.anchor_names)

    class CouncilDumper(yaml.SafeDumper):
        def generate_anchor(self, node):
            while True:
                anchor = super().generate_anchor(node)
                if anchor not in reserved_anchors:
                    reserved_anchors.add(anchor)
                    return anchor

    backend_indent = " " * backend_key.start_mark.column
    backend_yaml = yaml.dump({"llm_backends": backends}, Dumper=CouncilDumper, sort_keys=False)
    # The source prefix already supplies indentation before the first key.
    backend_yaml = indent(backend_yaml, backend_indent)[len(backend_indent) :]
    replacements = [
        (
            backend_key.start_mark.index,
            backend_end,
            backend_yaml + "\n",
        )
    ]
    for role in local_roles:
        node = role_nodes[role]
        replacements.append((node.start_mark.index, node.end_mark.index, "nim-local"))
    for event, node in loader.aliases:
        if (
            backend_key.start_mark.index <= node.start_mark.index < backend_end
            and not backend_key.start_mark.index <= event.start_mark.index < backend_end
        ):
            # Resolve references to removed anchors in hosted roles and policy.
            # Flow style and quoted scalars fit any original alias indentation.
            replacement = yaml.dump(
                loader.construct_document(node),
                Dumper=CouncilDumper,
                default_flow_style=True,
                default_style='"',
                width=float("inf"),
            ).strip()
            replacements.append((event.start_mark.index, event.end_mark.index, replacement))
    # YAML marks let us preserve policy text and role comments verbatim while
    # supporting arbitrary backend names, field ordering, and YAML indentation.
    result = source
    # Hosted roles may share a mapping, so apply each alias replacement once.
    for start, end, replacement in sorted(set(replacements), reverse=True):
        result = result[:start] + replacement + result[end:]
    try:
        yaml.safe_load(result)
    except yaml.YAMLError as exc:
        raise ValueError("rendered council YAML is invalid") from exc
    return GENERATED_MARKER + result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--local-model", required=True)
    parser.add_argument("--local-url", required=True)
    parser.add_argument("--mode", choices=("pure", "mixed"), required=True)
    parser.add_argument(
        "--local-roles",
        help=(
            "Comma-separated roles assigned to the local NIM in mixed mode; "
            "defaults to command-integrity,code_review,chairman"
        ),
    )
    args = parser.parse_args()
    if args.mode == "pure" and args.local_roles is not None:
        parser.error("--local-roles is only valid in mixed mode")
    roles = (
        set(ROLES)
        if args.mode == "pure"
        else set(args.local_roles.split(","))
        if args.local_roles is not None
        else set(DEFAULT_MIXED_LOCAL_ROLES)
    )
    if any(role != role.strip() or not role for role in roles):
        parser.error("--local-roles must contain nonempty role names without spaces")
    try:
        rendered = render(
            args.source.read_text(encoding="utf-8"),
            local_model=args.local_model,
            local_url=args.local_url,
            mode=args.mode,
            local_roles=roles,
        )
    except (OSError, ValueError) as exc:
        parser.error(str(exc))
    temp_path = None
    try:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            dir=args.output.parent,
            prefix=f".{args.output.name}.",
            suffix=".tmp",
            delete=False,
        ) as temp_file:
            temp_path = Path(temp_file.name)
            temp_file.write(rendered)
        # NamedTemporaryFile starts at 0600, but the council runs as a
        # different user and reads this bind-mounted profile after startup.
        temp_path.chmod(0o644)
        os.replace(temp_path, args.output)
    except OSError as exc:
        parser.error(str(exc))
    finally:
        if temp_path is not None:
            temp_path.unlink(missing_ok=True)
    print(f"Wrote {args.mode} council profile: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
